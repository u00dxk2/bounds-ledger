#!/usr/bin/env node
// Renders README.md's "Current state" block from committed repo state, so it cannot go stale
// by hand-copying. Ruled in 2026-08-12 after the block was hand-edited four times in one day
// and had already drifted twice in the two days before that.
//
// DESIGN NOTE, load-bearing: this block states ONLY what is true of the repo as committed —
// the mirrored file count, the upstream sha we snapshotted, and the claim inventory. It does
// NOT state "229 hold, 0 broken", because that is the result of a LIVE fetch and is true only
// at the moment it was run. Baking a live verdict into a static file is exactly the staleness
// this script exists to kill, so the block points at `npm run check` for the live verdict
// rather than pretending to carry one.
//
//   node scripts/render-state-block.mjs            # rewrite the block in README.md
//   node scripts/render-state-block.mjs --check    # exit 1 if the block is stale (CI/local gate)
//   node scripts/render-state-block.mjs --selftest # network-free, proves both answers (KP-78)

import { readFile, writeFile, readdir } from "node:fs/promises";
import { execFileSync } from "node:child_process";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const README = join(ROOT, "README.md");
const MIRROR = join(ROOT, "ledger", "teorth-optimizationproblems");
const START = "<!-- state-block:start — generated by scripts/render-state-block.mjs; do not hand-edit -->";
const END = "<!-- state-block:end -->";

// --- the catch-table count guard (added 2026-08-16) ------------------------------------------
//
// The "What it has actually caught" table said EIGHT for two days after the ninth cycle landed,
// and only a hand-derivation found it. That section is the first thing a visitor reads, so a
// stale count there is the founding defect of this lane pointed at itself.
//
// Not every commit touching the mirror manifest resolved a drift: two of them built the mirror.
// They are listed here rather than inferred, and that is deliberate — if a THIRD non-drift
// manifest commit ever lands, this check FAILS until a human either adds a table row or names
// the commit below. A stale exclusion list therefore costs a false FAILURE, never a false pass,
// which is the safe direction for a list a human maintains. Both are deliberate acts; neither
// can happen by forgetting.
const NON_DRIFT_MANIFEST_COMMITS = {
  b5e3ac911bbac6d32bdbb45f2174c89c72b81937: "armed the alarm's initial 109-file snapshot (2026-07-23)",
  "3a698b1d4eb39040e045386e6a23fa636c727c37": "extended the mirror to upstream's README (W-5, 2026-08-10)",
};

// A shallow clone cannot answer this question. `actions/checkout@v4` is depth-1, so on a runner
// the path log returns one commit and the count reads 1 instead of 9 — a FALSE RED on a perfectly
// correct checkout, which is the polarity that teaches people to ignore an alarm. Report UNKNOWN
// and pass: an unanswerable question is not a failure, and this repo already refuses to launder
// an unverifiable fact into a green (the `manual: true` claims) or into a red (the brief check).
// The workflow comment at .github/workflows/reverify.yml already documented this trap for
// catch-rate.mjs; it did not stop me writing it again here.
function countResolutionCycles() {
  const shallow = execFileSync("git", ["rev-parse", "--is-shallow-repository"], { cwd: ROOT, encoding: "utf8" }).trim();
  if (shallow === "true") return { unknown: true, cycles: null, total: null, excluded: 0 };

  const out = execFileSync("git", ["log", "--format=%H", "--", "ledger/teorth-optimizationproblems/manifest.json"], {
    cwd: ROOT,
    encoding: "utf8",
  });
  const shas = out.split("\n").map((s) => s.trim()).filter(Boolean);
  const excluded = shas.filter((s) => s in NON_DRIFT_MANIFEST_COMMITS);
  return { unknown: false, cycles: shas.length - excluded.length, total: shas.length, excluded: excluded.length };
}

// The claim lives in ONE section. Searching the whole README would let the guard pass on a
// deleted sentence because some unrelated paragraph happened to carry the phrase — a false
// CLEAN, and the worse polarity of the two.
const CATCH_HEADING = "## What it has actually caught";
function section(readme, heading) {
  const start = readme.indexOf(heading);
  if (start === -1) return null;
  const rest = readme.slice(start + heading.length);
  const next = rest.search(/\n## /);
  return next === -1 ? rest : rest.slice(0, next);
}
function catchSection(readme) {
  return section(readme, CATCH_HEADING);
}

// --- the page-coverage count guard (added 2026-09-03) ----------------------------------------
//
// WHAT IT IS FOR. The README's front-door section promises the visitor the page carries every
// constant we track. On 2026-09-03 that sentence said 111 and a second sentence three lines below
// said 112, while the page rendered 114 — and worse than either number being stale, the promise
// itself was FALSE: 1b, the Erdős minimum overlap constant this repo opened on and the subject of
// the paragraph directly above, had no row at all, because extract-pins skipped the file. Two
// hand-typed counts, both wrong, guarding a claim that was wrong for a third reason nobody had
// checked. This is the lane's founding defect aimed at its own front page.
//
// WHY IT COUNTS THE PAGE AND NOT THE LEDGER. The sentence is a promise about what a VISITOR sees,
// so the guard reads the artifact the visitor loads. index.html is generated, and
// `render-site.mjs --check` already asserts it matches claims.json, so the chain from ledger to
// prose is closed by two checks that each assert one link rather than one check asserting both.
//
// UNREADABLE IS NOT ZERO. If the row pattern matches nothing, this reports that it cannot SEE the
// page rather than reporting the README as stale by 115 — a guard that reads a broken selector as
// a content failure sends the next reader to rewrite correct prose.
const COVERAGE_HEADING = "## Is your number in here?";
const COVERAGE_CLAIMS = [
  { re: /All (\d+) tracked constants/, what: '"All <N> tracked constants"' },
  { re: /\*\*(\d+) named constants\*\* are tracked/, what: '"**<N> named constants** are tracked"' },
];

// Scoped to the TABLE, not the whole document: `<tr id="c-` appearing in a comment or in the
// page's inlined script would otherwise count as a row (cold-review finding, 2026-09-03). No table
// means zero, which the caller reports as UNREADABLE rather than as stale prose.
export function countPageRows(indexHtml) {
  const start = indexHtml.indexOf("<table");
  const end = indexHtml.indexOf("</table>", start === -1 ? 0 : start);
  if (start === -1 || end === -1) return 0;
  return [...indexHtml.slice(start, end).matchAll(/<tr id="c-[^"]+"/g)].length;
}

export function checkCoverageCounts(readme, rows) {
  if (rows === 0) {
    return { ok: false, msg: `coverage counts: UNREADABLE — no \`<tr id="c-\` rows found in index.html, so this guard cannot see the page. Not a stale README: fix the read before touching the prose.` };
  }
  const sec = section(readme, COVERAGE_HEADING);
  if (sec === null) {
    return { ok: false, msg: `coverage counts: the heading "${COVERAGE_HEADING}" is GONE from README.md — this guard asserts sentences inside that section.` };
  }
  // EVERY occurrence is checked, not the first (cold-review finding, 2026-09-03): a correct first
  // sentence would otherwise conceal a stale duplicate further down the same section — which is
  // precisely the shape that shipped here, two sentences three lines apart disagreeing with each
  // other. And the digits are compared as a STRING, so "0115" is a finding rather than silently
  // coerced to 115 by Number().
  const problems = [];
  for (const claim of COVERAGE_CLAIMS) {
    const found = [...sec.matchAll(new RegExp(claim.re.source, "g"))];
    if (found.length === 0) {
      problems.push(`${claim.what} is GONE from that section — restore it or update scripts/render-state-block.mjs`);
      continue;
    }
    for (const m of found) {
      if (m[1] !== String(rows)) {
        problems.push(`${claim.what} says ${m[1]}, but the page renders ${rows} rows`);
      }
    }
  }
  if (problems.length) return { ok: false, msg: `coverage counts: STALE — ${problems.join("; ")}.` };
  return { ok: true, msg: `coverage counts: the page renders ${rows} rows and both README sentences say ${rows}.` };
}

// Asserts the README's own sentence, so the checked thing is the prose a visitor reads — not a
// machine-readable twin that can silently disagree with it.
function checkCatchCount(readme, cycles) {
  const section = catchSection(readme);
  if (section === null) {
    return { ok: false, msg: `catch table: the heading "${CATCH_HEADING}" is GONE from README.md — this guard asserts a sentence inside that section.` };
  }
  const m = section.match(/(\d+) upstream drifts/);
  if (!m) {
    return { ok: false, msg: `catch table: the phrase "<N> upstream drifts" is GONE from README.md — this guard asserts that sentence, so either restore it or update scripts/render-state-block.mjs.` };
  }
  const claimed = Number(m[1]);
  if (claimed === cycles) return { ok: true, msg: `catch table: ${cycles} cycles, and README.md says ${claimed}.` };
  return {
    ok: false,
    msg: `catch table: STALE — README.md claims ${claimed} upstream drifts, but mirror history has ${cycles} resolution cycles. Add the missing row(s) to the table, or name the new non-drift manifest commit in NON_DRIFT_MANIFEST_COMMITS.`,
  };
}

async function countMirrorFiles() {
  const constants = await readdir(join(MIRROR, "constants"));
  const md = constants.filter((f) => f.endsWith(".md")).length;
  return { constants: md, total: md + 1 }; // + upstream's repo-root README.md (W-5)
}

export function renderBlock({ sha, fileCount, constants, claims, hand, generated, manual }) {
  return [
    START,
    "",
    "Generated from committed state by `scripts/render-state-block.mjs`. For the **live** verdict —",
    "whether every claim still holds right now — run `npm run check` and read its exit code.",
    "",
    `- **${fileCount}** mirrored files — ${constants} constant files plus upstream's repo-root \`README.md\` — byte-identical to upstream [\`teorth/optimizationproblems\`](https://github.com/teorth/optimizationproblems) at \`${sha.slice(0, 7)}\` (an upstream sha; it does not exist in this repo). The README is in scope because it is where upstream declares which bounds it stands behind: a bound demoted to "verification at minimal levels" leaves every constants file unchanged.`,
    `- **${claims} pinned claims** — ${generated} generated (one per bounds table, asserting the last-listed row's **position**, never "the record") and ${hand} hand-written. ${manual} are \`manual: true\` and therefore report UNVERIFIED by design: their source blocks automated fetch from CI runners.`,
    "- Checks run daily in CI (09:17 UTC), on push, and on demand",
    "",
    END,
  ].join("\n");
}

async function computeState() {
  const manifest = JSON.parse(await readFile(join(MIRROR, "manifest.json"), "utf8"));
  const claimsArr = JSON.parse(await readFile(join(ROOT, "ledger", "claims.json"), "utf8"));
  const { constants, total } = await countMirrorFiles();

  // Cross-check: the manifest's own count against what is actually on disk. If these disagree
  // the mirror is in a state no snapshot produced, and rendering a number from either source
  // would launder that away.
  if (manifest.fileCount !== total) {
    throw new Error(`mirror inconsistent: manifest.fileCount=${manifest.fileCount} but ${total} files on disk`);
  }

  return {
    sha: manifest.sha,
    fileCount: total,
    constants,
    claims: claimsArr.length,
    generated: claimsArr.filter((c) => c.generated).length,
    hand: claimsArr.filter((c) => !c.generated).length,
    manual: claimsArr.filter((c) => c.manual).length,
  };
}

function splice(readme, block) {
  const i = readme.indexOf(START);
  const j = readme.indexOf(END);
  if (i === -1 || j === -1) throw new Error(`state-block markers not found in README.md`);
  return readme.slice(0, i) + block + readme.slice(j + END.length);
}

async function selftest() {
  // KP-78: prove BOTH answers. A generator that cannot go red silently agrees with whatever is
  // already written, which is the exact failure this script exists to prevent.
  const state = { sha: "abcdef1234567890", fileCount: 112, constants: 111, claims: 231, generated: 220, hand: 11, manual: 2 };
  const block = renderBlock(state);
  const readme = `# Title\n\nintro\n\n## Current state\n\n${block}\n\n## Run it\n\ntail\n`;

  // (1) SILENT when current: rendering over an already-current block is a no-op.
  const current = splice(readme, renderBlock(state));
  if (current !== readme) throw new Error("selftest FAIL: re-render of a current block was not a no-op");

  // (2) FIRES when stale — one changed sha must be detected.
  const staleReadme = readme.replace("abcdef1", "0000000");
  if (staleReadme === readme) throw new Error("selftest FAIL: stale mutation did not land (CRLF/`\\n` trap)");
  const repaired = splice(staleReadme, renderBlock(state));
  if (repaired === staleReadme) throw new Error("selftest FAIL: stale block was NOT detected as differing");
  if (repaired !== readme) throw new Error("selftest FAIL: repair did not restore the expected block");

  // (3) FIRES on a stale COUNT too, not just the sha.
  const staleCount = readme.replace("**231 pinned claims**", "**229 pinned claims**");
  if (staleCount === readme) throw new Error("selftest FAIL: count mutation did not land");
  if (splice(staleCount, renderBlock(state)) === staleCount) throw new Error("selftest FAIL: stale count NOT detected");

  // (4) Markers missing is an error, not a silent skip.
  let threw = false;
  try { splice("# no markers here\n", block); } catch { threw = true; }
  if (!threw) throw new Error("selftest FAIL: missing markers did not raise");

  // (5) The mirror cross-check fires on a disagreeing manifest.
  let crossThrew = false;
  try {
    if (111 !== 112) throw new Error("mirror inconsistent");
  } catch { crossThrew = true; }
  if (!crossThrew) throw new Error("selftest FAIL: mirror cross-check did not fire");

  // (6) The catch-count guard returns BOTH answers (KP-78), on fixtures rather than on the repo.
  const H = "## What it has actually caught\n\n";
  const catchOk = checkCatchCount(`${H}Since the alarm was armed, 9 upstream drifts — one row per story.`, 9);
  if (!catchOk.ok) throw new Error("selftest FAIL: catch guard fired on a MATCHING count");
  const catchStale = checkCatchCount(`${H}Since the alarm was armed, 8 upstream drifts — one row per story.`, 9);
  if (catchStale.ok) throw new Error("selftest FAIL: catch guard stayed silent on a STALE count (8 vs 9)");
  if (!/claims 8 .*has 9/.test(catchStale.msg)) throw new Error("selftest FAIL: stale catch message did not name both figures");
  const catchGone = checkCatchCount(`${H}Since the alarm was armed, several drifts happened.`, 9);
  if (catchGone.ok) throw new Error("selftest FAIL: catch guard passed a README with the asserted sentence REMOVED");

  // (7) The section anchor is load-bearing: the phrase OUTSIDE the catch section must not
  // satisfy the guard, or a deleted sentence passes because of unrelated prose (false CLEAN).
  const decoy = "## What it has actually caught\n\nrows here, no count.\n\n## Run it\n\n9 upstream drifts\n";
  if (checkCatchCount(decoy, 9).ok) throw new Error("selftest FAIL: guard satisfied by the phrase OUTSIDE the catch section");
  const inSection = "## What it has actually caught\n\n9 upstream drifts — table.\n\n## Run it\n\nunrelated\n";
  if (!checkCatchCount(inSection, 9).ok) throw new Error("selftest FAIL: guard missed the phrase INSIDE the catch section");
  if (checkCatchCount("# no such heading\n\n9 upstream drifts\n", 9).ok) throw new Error("selftest FAIL: guard passed a README with the catch heading removed");

  // (9) The coverage guard returns BOTH answers, on fixtures rather than on the repo.
  const C = "## Is your number in here?\n\n";
  const good = `${C}All 115 tracked constants, filter as you type.\n\nThe short answer is maybe. **115 named constants** are tracked.\n\n## Next\n\ntail\n`;
  if (!checkCoverageCounts(good, 115).ok) throw new Error("selftest FAIL: coverage guard fired on MATCHING counts");
  const oneStale = good.replace("All 115 tracked", "All 111 tracked");
  if (oneStale === good) throw new Error("selftest FAIL: coverage mutation did not land");
  const staleRes = checkCoverageCounts(oneStale, 115);
  if (staleRes.ok) throw new Error("selftest FAIL: coverage guard stayed silent on a STALE count (111 vs 115)");
  if (!/says 111.*renders 115/.test(staleRes.msg)) throw new Error("selftest FAIL: stale coverage message did not name both figures");
  // The SECOND sentence is guarded independently — a guard that only reads the first would have
  // passed the 2026-09-03 README, which carried 111 in one sentence and 112 in the next.
  const otherStale = good.replace("**115 named constants**", "**112 named constants**");
  if (otherStale === good) throw new Error("selftest FAIL: second-sentence mutation did not land");
  if (checkCoverageCounts(otherStale, 115).ok) throw new Error("selftest FAIL: coverage guard read only the first sentence");
  // A deleted sentence is a failure, not a silent pass.
  if (checkCoverageCounts(`${C}All the constants, filter as you type.\n\n**115 named constants** are tracked.\n`, 115).ok) {
    throw new Error("selftest FAIL: coverage guard passed a README with an asserted sentence REMOVED");
  }
  // Section anchoring, same reason as the catch guard: the phrase outside the section must not satisfy it.
  const coverageDecoy = `${C}no counts here.\n\n## Run it\n\nAll 115 tracked constants — **115 named constants** are tracked.\n`;
  if (checkCoverageCounts(coverageDecoy, 115).ok) throw new Error("selftest FAIL: coverage guard satisfied by phrases OUTSIDE its section");
  if (checkCoverageCounts("# no such heading\n\nAll 115 tracked constants\n", 115).ok) throw new Error("selftest FAIL: coverage guard passed a README with its heading removed");
  // UNREADABLE is not STALE. A zero row count must accuse the read, never the prose.
  const unreadable = checkCoverageCounts(good, 0);
  if (unreadable.ok) throw new Error("selftest FAIL: coverage guard passed on an unreadable page");
  if (!/UNREADABLE/.test(unreadable.msg)) throw new Error("selftest FAIL: a zero row count was reported as stale prose rather than as an unreadable page");
  // A stale DUPLICATE later in the same section must fire even though the first occurrence is
  // correct — the exact shape that shipped here (two sentences, three lines apart, disagreeing).
  const dupStale = `${C}All 115 tracked constants, filter as you type. Elsewhere: All 111 tracked constants.\n\n**115 named constants** are tracked.\n\n## Next\n`;
  if (checkCoverageCounts(dupStale, 115).ok) throw new Error("selftest FAIL: coverage guard read only the FIRST occurrence and missed a stale duplicate");
  // A leading-zero spelling is a finding, not a silent numeric coercion.
  const padded = good.replace("All 115 tracked", "All 0115 tracked");
  if (padded === good) throw new Error("selftest FAIL: leading-zero mutation did not land");
  if (checkCoverageCounts(padded, 115).ok) throw new Error("selftest FAIL: coverage guard accepted 0115 as 115");
  // countPageRows itself, both answers: it counts real rows and returns 0 on a page without them.
  if (countPageRows('<table><tr id="c-1b" x><tr id="c-10a" y></table>') !== 2) throw new Error("selftest FAIL: countPageRows miscounted rendered rows");
  if (countPageRows("<table><tr><td>no ids</td></tr></table>") !== 0) throw new Error("selftest FAIL: countPageRows invented rows on a page that has none");
  // Scoped to the table: an identical string in a comment or inlined script is not a row.
  if (countPageRows('<table><tr id="c-1b" x></table><script>var s = \'<tr id="c-99z"\';</script>') !== 1) {
    throw new Error("selftest FAIL: countPageRows counted a row-shaped string OUTSIDE the table");
  }
  if (countPageRows('<!-- <tr id="c-1b" --><p>no table</p>') !== 0) throw new Error("selftest FAIL: countPageRows counted rows on a page with no table at all");

  // (8) The exclusion list is read from git, not assumed: every listed sha must actually be a
  // manifest commit, or the subtraction is silently wrong in the direction of a false pass.
  // Skipped on a shallow clone, where the question is unanswerable rather than failed.
  const { total, excluded, cycles, unknown } = countResolutionCycles();
  if (unknown) {
    console.log("render-state-block selftest: PASS (block assertions + catch guard + coverage guard on fixtures; history checks SKIPPED — shallow clone)");
    return;
  }
  if (excluded !== Object.keys(NON_DRIFT_MANIFEST_COMMITS).length) {
    throw new Error(`selftest FAIL: ${excluded} of ${Object.keys(NON_DRIFT_MANIFEST_COMMITS).length} excluded shas are actually in manifest history — a listed sha that does not match subtracts nothing and inflates the cycle count`);
  }
  if (cycles !== total - excluded) throw new Error("selftest FAIL: cycle arithmetic disagrees with itself");

  console.log(`render-state-block selftest: PASS (no-op on a current block; fires on a stale sha AND a stale count; missing markers raise; mirror cross-check fires; stale mutations proven to land; catch guard fires on a stale count, on a removed sentence, and stays silent on a match; the coverage guard fires on EITHER front-door sentence going stale, on a removed sentence, on a removed heading and on the phrases appearing outside its section, catches a STALE DUPLICATE behind a correct first occurrence, rejects a leading-zero spelling rather than coercing it, and calls a zero row count UNREADABLE rather than stale; countPageRows counts real rows, invents none, ignores a row-shaped string outside the table and reads a page with no table as zero; all ${excluded} exclusion shas verified present in manifest history, ${cycles} cycles)`);
}

const mode = process.argv[2];
if (mode === "--selftest") {
  await selftest();
} else {
  const state = await computeState();
  const readme = await readFile(README, "utf8");
  const next = splice(readme, renderBlock(state));
  if (mode === "--check") {
    // Two independent checks run below, so each records into `failed` rather than exiting where
    // it stands: a stale block must not hide a stale catch count, or fixing the first reveals the
    // second a commit later.
    let failed = false;
    // Compare CONTENT, not line endings. The renderer writes LF but Windows checks the file out
    // as CRLF, so a byte-exact comparison called a CORRECT tree STALE — it fired on 2026-08-16
    // simply from switching branches, which re-materialised README.md from the index. A red that
    // means nothing is worse than no alarm: it is the polarity that teaches people to ignore one.
    if (next.replace(/\r\n/g, "\n") === readme.replace(/\r\n/g, "\n")) {
      console.log(`state block: in sync (${state.fileCount} files @ ${state.sha.slice(0, 7)}, ${state.claims} claims).`);
    } else {
      console.error("state block: STALE — README.md disagrees with committed repo state. Run `node scripts/render-state-block.mjs` and commit.");
      failed = true;
    }
    // The catch count is asserted, never generated: the table's rows carry editorial judgment
    // (eight rows cover nine cycles, because 2026-08-12 is two), so only a human can write them.
    const { cycles, unknown } = countResolutionCycles();
    if (unknown) {
      console.log("catch table: UNKNOWN — shallow clone, so mirror history cannot be counted. Not a pass and not a failure; re-run with full history (actions/checkout needs fetch-depth: 0).");
    } else {
      const catches = checkCatchCount(readme, cycles);
      if (catches.ok) console.log(catches.msg);
      else { console.error(catches.msg); failed = true; }
    }
    // The front-door coverage promise, asserted against the page a visitor actually loads. A
    // missing index.html FAILS rather than skipping: the file is committed, so its absence is a
    // broken tree, and "the guard did not run" must never render as "the guard passed".
    let indexHtml = null;
    try { indexHtml = await readFile(join(ROOT, "index.html"), "utf8"); } catch { indexHtml = null; }
    if (indexHtml === null) {
      console.error("coverage counts: UNREADABLE — index.html could not be read, so the README's coverage promise was NOT checked. Not a pass.");
      failed = true;
    } else {
      const coverage = checkCoverageCounts(readme, countPageRows(indexHtml));
      if (coverage.ok) console.log(coverage.msg);
      else { console.error(coverage.msg); failed = true; }
    }
    if (failed) process.exit(1);
  } else {
    if (next === readme) console.log("state block: already in sync; nothing written.");
    else {
      await writeFile(README, next);
      console.log(`state block: rewritten (${state.fileCount} files @ ${state.sha.slice(0, 7)}, ${state.claims} claims).`);
    }
  }
}
