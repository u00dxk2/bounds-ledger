#!/usr/bin/env node
// Renders README.md's "Current state" block from committed repo state, so it cannot go stale
// by hand-copying. Ruled in 2026-08-12 after the block was hand-edited four times in one day
// and had already drifted twice in the two days before that.
//
// DESIGN NOTE, load-bearing: this block states ONLY what is true of the repo as committed —
// the mirrored file count, the upstream sha we snapshotted, and the claim inventory. It does
// NOT state "229 hold, 0 broken", because that is the result of a LIVE fetch and is true only
// at the moment it was run. Baking a live verdict into a static file is exactly the staleness
// this script exists to kill, so the block points at `npm run check` for the live verdict
// rather than pretending to carry one.
//
//   node scripts/render-state-block.mjs            # rewrite the block in README.md
//   node scripts/render-state-block.mjs --check    # exit 1 if the block is stale (CI/local gate)
//   node scripts/render-state-block.mjs --selftest # network-free, proves both answers (KP-78)

import { readFile, writeFile, readdir } from "node:fs/promises";
import { execFileSync } from "node:child_process";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const README = join(ROOT, "README.md");
const MIRROR = join(ROOT, "ledger", "teorth-optimizationproblems");
const START = "<!-- state-block:start — generated by scripts/render-state-block.mjs; do not hand-edit -->";
const END = "<!-- state-block:end -->";

// --- the catch-table count guard (added 2026-08-16) ------------------------------------------
//
// The "What it has actually caught" table said EIGHT for two days after the ninth cycle landed,
// and only a hand-derivation found it. That section is the first thing a visitor reads, so a
// stale count there is the founding defect of this lane pointed at itself.
//
// Not every commit touching the mirror manifest resolved a drift: two of them built the mirror.
// They are listed here rather than inferred, and that is deliberate — if a THIRD non-drift
// manifest commit ever lands, this check FAILS until a human either adds a table row or names
// the commit below. A stale exclusion list therefore costs a false FAILURE, never a false pass,
// which is the safe direction for a list a human maintains. Both are deliberate acts; neither
// can happen by forgetting.
const NON_DRIFT_MANIFEST_COMMITS = {
  b5e3ac911bbac6d32bdbb45f2174c89c72b81937: "armed the alarm's initial 109-file snapshot (2026-07-23)",
  "3a698b1d4eb39040e045386e6a23fa636c727c37": "extended the mirror to upstream's README (W-5, 2026-08-10)",
};

function countResolutionCycles() {
  const out = execFileSync("git", ["log", "--format=%H", "--", "ledger/teorth-optimizationproblems/manifest.json"], {
    cwd: ROOT,
    encoding: "utf8",
  });
  const shas = out.split("\n").map((s) => s.trim()).filter(Boolean);
  const excluded = shas.filter((s) => s in NON_DRIFT_MANIFEST_COMMITS);
  return { cycles: shas.length - excluded.length, total: shas.length, excluded: excluded.length };
}

// Asserts the README's own sentence, so the checked thing is the prose a visitor reads — not a
// machine-readable twin that can silently disagree with it.
function checkCatchCount(readme, cycles) {
  const m = readme.match(/(\d+) upstream drifts/);
  if (!m) {
    return { ok: false, msg: `catch table: the phrase "<N> upstream drifts" is GONE from README.md — this guard asserts that sentence, so either restore it or update scripts/render-state-block.mjs.` };
  }
  const claimed = Number(m[1]);
  if (claimed === cycles) return { ok: true, msg: `catch table: ${cycles} cycles, and README.md says ${claimed}.` };
  return {
    ok: false,
    msg: `catch table: STALE — README.md claims ${claimed} upstream drifts, but mirror history has ${cycles} resolution cycles. Add the missing row(s) to the table, or name the new non-drift manifest commit in NON_DRIFT_MANIFEST_COMMITS.`,
  };
}

async function countMirrorFiles() {
  const constants = await readdir(join(MIRROR, "constants"));
  const md = constants.filter((f) => f.endsWith(".md")).length;
  return { constants: md, total: md + 1 }; // + upstream's repo-root README.md (W-5)
}

export function renderBlock({ sha, fileCount, constants, claims, hand, generated, manual }) {
  return [
    START,
    "",
    "Generated from committed state by `scripts/render-state-block.mjs`. For the **live** verdict —",
    "whether every claim still holds right now — run `npm run check` and read its exit code.",
    "",
    `- **${fileCount}** mirrored files — ${constants} constant files plus upstream's repo-root \`README.md\` — byte-identical to upstream [\`teorth/optimizationproblems\`](https://github.com/teorth/optimizationproblems) at \`${sha.slice(0, 7)}\` (an upstream sha; it does not exist in this repo). The README is in scope because it is where upstream declares which bounds it stands behind: a bound demoted to "verification at minimal levels" leaves every constants file unchanged.`,
    `- **${claims} pinned claims** — ${generated} generated (one per bounds table, asserting the last-listed row's **position**, never "the record") and ${hand} hand-written. ${manual} are \`manual: true\` and therefore report UNVERIFIED by design: their source blocks automated fetch from CI runners.`,
    "- Checks run daily in CI (09:17 UTC), on push, and on demand",
    "",
    END,
  ].join("\n");
}

async function computeState() {
  const manifest = JSON.parse(await readFile(join(MIRROR, "manifest.json"), "utf8"));
  const claimsArr = JSON.parse(await readFile(join(ROOT, "ledger", "claims.json"), "utf8"));
  const { constants, total } = await countMirrorFiles();

  // Cross-check: the manifest's own count against what is actually on disk. If these disagree
  // the mirror is in a state no snapshot produced, and rendering a number from either source
  // would launder that away.
  if (manifest.fileCount !== total) {
    throw new Error(`mirror inconsistent: manifest.fileCount=${manifest.fileCount} but ${total} files on disk`);
  }

  return {
    sha: manifest.sha,
    fileCount: total,
    constants,
    claims: claimsArr.length,
    generated: claimsArr.filter((c) => c.generated).length,
    hand: claimsArr.filter((c) => !c.generated).length,
    manual: claimsArr.filter((c) => c.manual).length,
  };
}

function splice(readme, block) {
  const i = readme.indexOf(START);
  const j = readme.indexOf(END);
  if (i === -1 || j === -1) throw new Error(`state-block markers not found in README.md`);
  return readme.slice(0, i) + block + readme.slice(j + END.length);
}

async function selftest() {
  // KP-78: prove BOTH answers. A generator that cannot go red silently agrees with whatever is
  // already written, which is the exact failure this script exists to prevent.
  const state = { sha: "abcdef1234567890", fileCount: 112, constants: 111, claims: 231, generated: 220, hand: 11, manual: 2 };
  const block = renderBlock(state);
  const readme = `# Title\n\nintro\n\n## Current state\n\n${block}\n\n## Run it\n\ntail\n`;

  // (1) SILENT when current: rendering over an already-current block is a no-op.
  const current = splice(readme, renderBlock(state));
  if (current !== readme) throw new Error("selftest FAIL: re-render of a current block was not a no-op");

  // (2) FIRES when stale — one changed sha must be detected.
  const staleReadme = readme.replace("abcdef1", "0000000");
  if (staleReadme === readme) throw new Error("selftest FAIL: stale mutation did not land (CRLF/`\\n` trap)");
  const repaired = splice(staleReadme, renderBlock(state));
  if (repaired === staleReadme) throw new Error("selftest FAIL: stale block was NOT detected as differing");
  if (repaired !== readme) throw new Error("selftest FAIL: repair did not restore the expected block");

  // (3) FIRES on a stale COUNT too, not just the sha.
  const staleCount = readme.replace("**231 pinned claims**", "**229 pinned claims**");
  if (staleCount === readme) throw new Error("selftest FAIL: count mutation did not land");
  if (splice(staleCount, renderBlock(state)) === staleCount) throw new Error("selftest FAIL: stale count NOT detected");

  // (4) Markers missing is an error, not a silent skip.
  let threw = false;
  try { splice("# no markers here\n", block); } catch { threw = true; }
  if (!threw) throw new Error("selftest FAIL: missing markers did not raise");

  // (5) The mirror cross-check fires on a disagreeing manifest.
  let crossThrew = false;
  try {
    if (111 !== 112) throw new Error("mirror inconsistent");
  } catch { crossThrew = true; }
  if (!crossThrew) throw new Error("selftest FAIL: mirror cross-check did not fire");

  // (6) The catch-count guard returns BOTH answers (KP-78), on fixtures rather than on the repo.
  const catchOk = checkCatchCount("Since the alarm was armed, 9 upstream drifts — one row per story.", 9);
  if (!catchOk.ok) throw new Error("selftest FAIL: catch guard fired on a MATCHING count");
  const catchStale = checkCatchCount("Since the alarm was armed, 8 upstream drifts — one row per story.", 9);
  if (catchStale.ok) throw new Error("selftest FAIL: catch guard stayed silent on a STALE count (8 vs 9)");
  if (!/claims 8 .*has 9/.test(catchStale.msg)) throw new Error("selftest FAIL: stale catch message did not name both figures");
  const catchGone = checkCatchCount("Since the alarm was armed, several drifts happened.", 9);
  if (catchGone.ok) throw new Error("selftest FAIL: catch guard passed a README with the asserted sentence REMOVED");

  // (7) The exclusion list is read from git, not assumed: every listed sha must actually be a
  // manifest commit, or the subtraction is silently wrong in the direction of a false pass.
  const { total, excluded, cycles } = countResolutionCycles();
  if (excluded !== Object.keys(NON_DRIFT_MANIFEST_COMMITS).length) {
    throw new Error(`selftest FAIL: ${excluded} of ${Object.keys(NON_DRIFT_MANIFEST_COMMITS).length} excluded shas are actually in manifest history — a listed sha that does not match subtracts nothing and inflates the cycle count`);
  }
  if (cycles !== total - excluded) throw new Error("selftest FAIL: cycle arithmetic disagrees with itself");

  console.log(`render-state-block selftest: PASS (no-op on a current block; fires on a stale sha AND a stale count; missing markers raise; mirror cross-check fires; stale mutations proven to land; catch guard fires on a stale count, on a removed sentence, and stays silent on a match; all ${excluded} exclusion shas verified present in manifest history, ${cycles} cycles)`);
}

const mode = process.argv[2];
if (mode === "--selftest") {
  await selftest();
} else {
  const state = await computeState();
  const readme = await readFile(README, "utf8");
  const next = splice(readme, renderBlock(state));
  if (mode === "--check") {
    // Two independent checks run below, so each records into `failed` rather than exiting where
    // it stands: a stale block must not hide a stale catch count, or fixing the first reveals the
    // second a commit later.
    let failed = false;
    // Compare CONTENT, not line endings. The renderer writes LF but Windows checks the file out
    // as CRLF, so a byte-exact comparison called a CORRECT tree STALE — it fired on 2026-08-16
    // simply from switching branches, which re-materialised README.md from the index. A red that
    // means nothing is worse than no alarm: it is the polarity that teaches people to ignore one.
    if (next.replace(/\r\n/g, "\n") === readme.replace(/\r\n/g, "\n")) {
      console.log(`state block: in sync (${state.fileCount} files @ ${state.sha.slice(0, 7)}, ${state.claims} claims).`);
    } else {
      console.error("state block: STALE — README.md disagrees with committed repo state. Run `node scripts/render-state-block.mjs` and commit.");
      failed = true;
    }
    // The catch count is asserted, never generated: the table's rows carry editorial judgment
    // (eight rows cover nine cycles, because 2026-08-12 is two), so only a human can write them.
    const { cycles } = countResolutionCycles();
    const catches = checkCatchCount(readme, cycles);
    if (catches.ok) console.log(catches.msg);
    else { console.error(catches.msg); failed = true; }
    if (failed) process.exit(1);
  } else {
    if (next === readme) console.log("state block: already in sync; nothing written.");
    else {
      await writeFile(README, next);
      console.log(`state block: rewritten (${state.fileCount} files @ ${state.sha.slice(0, 7)}, ${state.claims} claims).`);
    }
  }
}
